def lesson_access(row: Optional[sqlite3.Row], idx: int, unlimited: bool = False) -> str:
    """'open' (можно открыть) / 'done' (уже открывался) / 'wait' (появится через
    сутки) / 'locked' (сначала пройди предыдущие). unlimited снимает только
    'wait' (суточный таймер) — порядок уроков (locked) остаётся ВСЕГДА, иначе
    можно перепрыгнуть с 1-го урока сразу на 7-й."""
    lesson_index = row["lesson_index"] if row else 0
    if idx == 0:
        return "done" if lesson_index > 0 else "open"
    if idx < lesson_index:
        return "done"
    if idx == lesson_index:
        if unlimited:
            return "open"
        unlocked_at = row["unlocked_at"] if row else int(time.time())
        if int(time.time()) >= unlocked_at + DAILY_UNLOCK_HOURS * 3600:
            return "open"
        return "wait"
    return "locked"


